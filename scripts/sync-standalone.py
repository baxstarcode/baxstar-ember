#!/usr/bin/env python3
"""Generate the local preview harness from the canonical JSX.

python3 only — no Node, no npm. This is the fast local loop:

    ./start-ember.sh          # regenerates _preview.html, then serves it

Scope note: this script owns **_preview.html only**. The deploy build
(index.html) is owned by build.mjs and nothing else writes it. Two generators
for one file is how index.html once drifted an entire redesign behind the
source without anyone noticing — don't reintroduce that.

Differences from the deploy build, on purpose:
  · Tailwind comes from the Play CDN, so there's no compile step here.
  · React dev builds, for readable component stack traces.
Both are right for local iteration and wrong for production. Run
`npm run build` for the artifact you actually host.
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src" / "baxstar-ember.jsx"
TARGET = ROOT / "_preview.html"

# The deployed Worker. Declared once here and written into BOTH generated surfaces,
# so the preview and the deploy build can never disagree about where the brain lives.
# Not a secret: the Worker enforces its origin allowlist server-side.
PROXY_URL = "https://ember-claude-proxy.brady-9d1.workers.dev"

IMPORT_LINE = 'import { useState, useEffect, useRef } from "react";'
EXPORT_LINE = "export default function BaxstarEmber"

HEAD = """<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
  <meta name="theme-color" content="#070604">
  <title>Ember — local preview</title>
  <!-- GENERATED by scripts/sync-standalone.py — do not edit.
       Local preview only. The hosted build is index.html, from `npm run build`. -->
  <link rel="icon" href="assets/ember/icon.svg" type="image/svg+xml"/>
<link rel="manifest" href="manifest.webmanifest">
  <link rel="apple-touch-icon" href="assets/ember/icon.svg">
  <script src="https://cdn.tailwindcss.com"></script>
  <script src="https://unpkg.com/react@18/umd/react.development.js"></script>
  <script src="https://unpkg.com/react-dom@18/umd/react-dom.development.js"></script>
  <script src="https://unpkg.com/@babel/standalone@7/babel.min.js"></script>
  <!-- HEIC->JPEG decoder for the caption tool. Preview-only: it's a third-party CDN, so
       the self-contained deploy build (index.html) intentionally omits it — the app
       feature-detects window.heic2any and degrades gracefully without it. -->
  <script src="https://cdn.jsdelivr.net/npm/heic2any@0.0.4/dist/heic2any.min.js"></script>
  <style>html,body,#root{margin:0;height:100%;background:#000;}</style>
  <script>
  /* Brady's deployed proxy — this is what gives the local preview a working brain.
     Not a secret: the Worker enforces an origin allowlist server-side, so this URL is
     useless from anywhere but ALLOWED_ORIGINS. Verified 403 from curl and from a
     forged origin. See docs/DEPLOY.md. */
  window.EMBER_API_PROXY = "__PROXY_URL__";
  </script>
  <script>
  /* PWA: cache the shell so repeat opens are instant on weak lake signal.
     Feature-detected — a no-op where service workers are unavailable. */
  if ("serviceWorker" in navigator) {
    window.addEventListener("load", function () {
      navigator.serviceWorker.register("sw.js", { updateViaCache: "none" })
        .then(function (registration) { return registration.update(); })
        .catch(function () {});
    });
  }
  </script>
</head>
<body>
  <div id="root"></div>
  <script type="text/babel" data-presets="react">
"""

FOOT = """
ReactDOM.createRoot(document.getElementById("root")).render(
  React.createElement(BaxstarEmber)
);
  </script>
</body>
</html>
"""


def browser_source() -> str:
    source = SOURCE.read_text(encoding="utf-8")
    if IMPORT_LINE not in source:
        raise SystemExit(f"sync: expected import line not found in {SOURCE}\n  {IMPORT_LINE}")
    if EXPORT_LINE not in source:
        raise SystemExit(f"sync: expected '{EXPORT_LINE}' not found in {SOURCE}")
    # An inline <script> ends at this sequence wherever it appears.
    if "</script" in source:
        raise SystemExit("sync: source contains a literal </script — it cannot be inlined safely")

    source = source.replace(IMPORT_LINE, "const { useState, useEffect, useRef } = React;", 1)
    source = source.replace(EXPORT_LINE, "function BaxstarEmber", 1)
    return source



TARGET.write_text(HEAD.replace("__PROXY_URL__", PROXY_URL) + browser_source() + FOOT, encoding="utf-8")
print(f"sync: wrote {TARGET.name} ({TARGET.stat().st_size // 1024}KB) from src/baxstar-ember.jsx")
